// Checkpoint quizzes for every level (1–8).
//
// SERVER ONLY. This module holds the answer keys, so importing it from a client
// component ships them to the browser. Client code imports `quiz-public.ts`
// instead and submits attempts to /api/grade/quiz/submit for grading.
//
// Every question is drawn from a claim the chapters actually make, and every
// explanation says why the wrong answers are wrong — a quiz that only rewards
// recall would contradict the course's own stance on evidence.
//
// Each attempt draws `askCount` questions at random from the bank, so retaking
// re-tests understanding instead of memorised answer positions.

import type {
  GradedQuestion,
  PublicQuizQuestion,
  QuizMeta,
} from "./quiz-public";

export type QuizQuestion =
  | {
      id: string;
      type: "choice";
      prompt: string;
      /** Optional scenario shown above the choices. */
      setup?: string;
      choices: string[];
      /** Index into `choices`. */
      answer: number;
      explain: string;
      ref: string;
    }
  | {
      id: string;
      type: "numeric";
      prompt: string;
      setup?: string;
      answer: number;
      /** Absolute tolerance applied to the answer. */
      tolerance: number;
      unit?: string;
      explain: string;
      ref: string;
    };

