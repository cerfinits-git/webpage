export function getQuiz(level: number): LevelQuiz | undefined {
  return QUIZZES.find((q) => q.level === level);
}

/**
 * Levels 5–8 are premium. Their quizzes stay gated because the explanations
 * restate the paid chapters — leaving them open would give the content away.
 */
export function isPremiumQuiz(level: number): boolean {
  return level >= 5;
}

/** Draw a random subset of the bank for one attempt. */
export function drawQuestions(quiz: LevelQuiz): QuizQuestion[] {
  const pool = [...quiz.bank];
  for (let i = pool.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }
  return pool.slice(0, Math.min(quiz.askCount, pool.length));
}

export function isCorrect(question: QuizQuestion, response: number | null): boolean {
  if (response == null) return false;
  if (question.type === "numeric") return Math.abs(response - question.answer) <= question.tolerance;
  return response === question.answer;
}

export function getQuizMeta(level: number): QuizMeta | undefined {
  const quiz = getQuiz(level);
  if (!quiz) return undefined;
  const { level: n, title, intro, askCount, passPercent } = quiz;
  return { level: n, title, intro, askCount, passPercent };
}

/** Strip a question down to what the browser may see before grading. */
export function toPublicQuestion(question: QuizQuestion): PublicQuizQuestion {
  if (question.type === "choice") {
    return {
      id: question.id,
      type: "choice",
      prompt: question.prompt,
      setup: question.setup,
      choices: question.choices,
    };
  }
  return {
    id: question.id,
    type: "numeric",
    prompt: question.prompt,
    setup: question.setup,
    unit: question.unit,
  };
}

export function drawPublicQuestions(quiz: LevelQuiz): PublicQuizQuestion[] {
  return drawQuestions(quiz).map(toPublicQuestion);
}

export type GradeAttemptOutcome =
  | {
      ok: true;
      percent: number;
      correctCount: number;
      total: number;
      passed: boolean;
      graded: GradedQuestion[];
    }
  | { ok: false; error: string };

/**
 * Grade one attempt on the server.
 *
 * The browser says which questions it was asked, so every claim it makes is
 * re-checked here: the ids must exist in this level's bank, must not repeat,
 * and must number exactly `askCount`. Without those checks a caller could
 * submit a single question it knew the answer to and score 100%.
 */
export function gradeAttempt(
  level: number,
  questionIds: unknown,
  responses: unknown,
): GradeAttemptOutcome {
  const quiz = getQuiz(level);
  if (!quiz) return { ok: false, error: "ไม่พบแบบทดสอบระดับนี้" };

  if (!Array.isArray(questionIds) || questionIds.some((id) => typeof id !== "string")) {
    return { ok: false, error: "รูปแบบคำถามไม่ถูกต้อง" };
  }
  const ids = questionIds as string[];

  const expected = Math.min(quiz.askCount, quiz.bank.length);
  if (ids.length !== expected) {
    return { ok: false, error: `ต้องตอบให้ครบ ${expected} ข้อ` };
  }
  if (new Set(ids).size !== ids.length) {
    return { ok: false, error: "มีคำถามซ้ำในชุดคำตอบ" };
  }

  const questions: QuizQuestion[] = [];
  for (const id of ids) {
    const question = quiz.bank.find((q) => q.id === id);
    if (!question) return { ok: false, error: "พบคำถามที่ไม่อยู่ในระดับนี้" };
    questions.push(question);
  }

  const answerMap = (responses ?? {}) as Record<string, unknown>;
  const graded: GradedQuestion[] = questions.map((question) => {
    const raw = answerMap[question.id];
    const response = typeof raw === "number" && Number.isFinite(raw) ? raw : null;
    return {
      id: question.id,
      correct: isCorrect(question, response),
      answer: question.answer,
      explain: question.explain,
      ref: question.ref,
    };
  });

  const correctCount = graded.filter((g) => g.correct).length;
  const percent = Math.round((correctCount / questions.length) * 100);

  return {
    ok: true,
    percent,
    correctCount,
    total: questions.length,
    passed: percent >= quiz.passPercent,
    graded,
  };
}
