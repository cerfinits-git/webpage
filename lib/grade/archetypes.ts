/** ต่ำกว่าเท่านี้ (สเกล 0–100) ถือว่าอยู่กลางแกน ตัวอักษรนั้นไม่มั่นคง */
export const DEAD_ZONE = 15;

export type AxisResult = {
  axis: Axis;
  /** −100..+100 — ลบคือฝั่ง negative ของแกน */
  score: number;
  side: { code: PoleCode; label: string };
  /** true = อยู่ใกล้กลางแกน ต้องแจ้งผู้ใช้ว่าตัวอักษรนี้พลิกได้ */
  borderline: boolean;
};

export type QuizResult = {
  code: string;
  archetype: Archetype;
  axes: Record<AxisId, AxisResult>;
  /** แกนที่คะแนนอยู่กลาง — ใช้บอกผู้ใช้ว่าตัวอักษรใดพลิกได้ */
  borderlineAxes: AxisId[];
  borderline: boolean;
  /** หลักฐานของขั้วที่ขับความเสี่ยงหลักของประเภทนี้ */
  dominantRisk: (typeof POLE_RISK)[PoleCode];
};

/** คะแนนดิบสูงสุดต่อแกน = จำนวนคำถามในแกนนั้น × 2 */
export function maxRawFor(axis: AxisId) {
  return QUESTIONS.filter((q) => q.axis === axis).length * 2;
}

/**
 * แปลงคำตอบเป็นผลลัพธ์ คำตอบที่ยังไม่ตอบให้ข้ามไป (นับเป็น 0) เพื่อให้คำนวณ
 * ระหว่างทางได้ แต่หน้าเว็บจะไม่แสดงผลจนตอบครบ
 */
export function scoreQuiz(answers: Record<string, number>): QuizResult {
  const axes = {} as Record<AxisId, AxisResult>;
  const borderlineAxes: AxisId[] = [];

  for (const id of AXIS_ORDER) {
    const axis = AXES[id];
    const raw = QUESTIONS.filter((q) => q.axis === id).reduce(
      (sum, q) => sum + (answers[q.id] ?? 0),
      0,
    );
    const score = Math.round((raw / maxRawFor(id)) * 100);
    const borderline = Math.abs(score) <= DEAD_ZONE;
    axes[id] = {
      axis,
      score,
      // คะแนน 0 พอดีตกไปฝั่ง negative และถูกทำเครื่องหมาย borderline อยู่แล้ว
      side: score > 0 ? axis.positive : axis.negative,
      borderline,
    };
    if (borderline) borderlineAxes.push(id);
  }

  const code = AXIS_ORDER.map((id) => axes[id].side.code).join("");
  const archetype = ARCHETYPES[code];

  return {
    code,
    archetype,
    axes,
    borderlineAxes,
    borderline: borderlineAxes.length > 0,
    dominantRisk: POLE_RISK[archetype.dominant],
  };
}

export function getArchetype(code: string): Archetype | null {
  return ARCHETYPES[code] ?? null;
}

export type FrameColour = "green" | "purple" | "navy" | "gold";

/**
 * สีกรอบของการ์ดถูกกำหนดโดยแกนที่ 1 (ตัด/ถือ) คูณแกนที่ 3 (คงวิธี/เปลี่ยนวิธี)
 *
 * สองแกนนี้คือแกนที่บอกว่า "ความเสียหายจะมาถึงอย่างไร" — ถือขาดทุนทำให้เสียหนัก
 * ครั้งเดียว เปลี่ยนวิธีบ่อยทำให้ไม่มีข้อมูลให้เรียนรู้ สีจึงไม่ใช่ของประดับ
 * แต่บอกกลุ่มความเสี่ยง และทำให้ 16 ประเภทใช้กรอบแค่ 4 แบบ
 */
export function frameFor(code: string): FrameColour {
  const holds = code[0] === "H";
  const revises = code[2] === "R";
  if (!holds) return revises ? "purple" : "green";
  return revises ? "gold" : "navy";
}

/** รหัสทั้ง 16 แบบ เรียงตามลำดับแกน — ใช้ตรวจความครบถ้วนในเทสต์ */
export function allCodes(): string[] {
  const codes: string[] = [];
  for (const a of [AXES.loss.negative.code, AXES.loss.positive.code]) {
    for (const b of [AXES.confidence.negative.code, AXES.confidence.positive.code]) {
      for (const c of [AXES.consistency.negative.code, AXES.consistency.positive.code]) {
        for (const d of [AXES.source.negative.code, AXES.source.positive.code]) {
          codes.push(`${a}${b}${c}${d}`);
        }
      }
    }
  }
  return codes;
}
